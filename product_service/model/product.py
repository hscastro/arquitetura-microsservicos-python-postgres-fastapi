
class Product:

    def __init__(self, id, name, description, price, category, created_at):
        self.id = id                      # Atributo de instância
        self.name = name                  # Atributo de instância
        self.description = description    # Atributo de instância
        self.price = price                # Atributo de instância
        self.category = category          # Atributo de instância
        self.created_at = created_at      # Atributo de instância


